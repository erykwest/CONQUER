'use strict';
// Ships: five Blender models (three small, two large) in src/assets/ship-models.js are
// listed in the Asset Lab, sized in proportion (large ships much longer than small
// craft), float with the hull below the waterline and masts above it, and are placed in
// the world by ConquerShips.mesh.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const lab=read('figures-lab.html');
assert.ok(lab.indexOf('src="./src/assets/ship-models.js')>0&&lab.indexOf('src="./src/assets/ship-models.js')<lab.indexOf('src="./src/settlement-ships.js'),'Asset Lab loads the models, then the runtime');
assert.match(read('src/asset-catalog.js'),/global:'ConquerShipModels',collection:'lab'/,'Asset Lab lists the ships');
for(const k of ['barca','cargo','caravella','cocca','nave'])
  assert.ok(lab.includes('data-subject="ship:'+k+'"'),'Asset Lab animates the sails of '+k);
assert.match(read('src/assets/ship-models.js'),/Generated by tools\/blender\/build_ships\.py/,'models come from the Blender builder');

const window={};
const ctx=vm.createContext({window,Math,Object,Number,Array,String});
for(const f of ['heraldry-shapes.js','assets/ship-models.js','settlement-ships.js'])vm.runInContext(read('src/'+f),ctx);
const M=window.ConquerShipModels,S=window.ConquerShips;
assert.equal(S.small.join(),'barca,cargo,caravella','three small craft');
assert.equal(S.large.join(),'cocca,nave','two large ships');
for(const [key,m] of Object.entries(M.ships)){
  assert.equal(m.i.length,m.c.length*3,key+': three indices per triangle');
  assert.ok(m.c.every(c=>c>=0&&c<M.palette.length),key+': palette colours');
  const zs=m.p.filter((_,i)=>i%3===2),xs=m.p.filter((_,i)=>i%3===0);
  assert.ok(Math.min(...zs)<-.15,key+': hull below the waterline');
  assert.ok(Math.max(...zs)>1.5,key+': mast and sail above the deck');
  assert.ok(Math.max(...xs)-Math.min(...xs)>=m.L*.95,key+': hull length');
}
// Sails: set and furled builds are the same triangles; furled, the cloth is up at the yards.
const span=a=>{let lo=Infinity,hi=-Infinity;for(let i=2;i<a.length;i+=3){lo=Math.min(lo,a[i]);hi=Math.max(hi,a[i])}return hi-lo};
for(const [key,m] of Object.entries(M.ships)){
  const s=m.sails;
  assert.ok(s.c.length>100,key+': has sails');
  assert.equal(s.v.length,s.c.length*9,key+': set sails, one colour per triangle');
  assert.equal(s.f.length,s.v.length,key+': furled sails match the set ones triangle by triangle');
  const meanZ=a=>{let t=0,n=0;for(let i=2;i<a.length;i+=3){t+=a[i];n++}return t/n};
  assert.ok(meanZ(s.f)>meanZ(s.v)+.15,key+': furled cloth is gathered up towards the yards');
  assert.ok(M.lab[key]&&M.lab[key+'Furled'],key+': Asset Lab shows it with sails set and furled');
}
const zs=(key,f)=>span(S.mesh(key,{x:0,y:0},f).pos);
assert.ok(zs('cocca',0)>=zs('cocca',1)-1e-9,'mesh() morphs the sails');
const st=S.sailState();S.raise(st);
for(let i=0;i<10;i++)S.step(st,S.SAIL_TIME/20);
assert.ok(st.furl>.3&&st.furl<.7,'half way through raising after half the sail time');
for(let i=0;i<20;i++)S.step(st,S.SAIL_TIME/10);
assert.equal(st.furl,1,'raised');S.lower(st);for(let i=0;i<20;i++)S.step(st,S.SAIL_TIME/10);
assert.equal(st.furl,0,'lowered again');
assert.equal(S.cycle(0),0,'the preview loop starts with sails set');
assert.equal(S.cycle(S.SAIL_TIME+.5),1,'then holds them raised');
// Heraldry: player / foreign warships wear their realm's arms on flags and sails; merchants
// fly the flag of their realm but keep plain sails.
const H=window.ConquerHeraldryShapes;
assert.equal(S.arms({allegiance:'player'}).sail.c1,H.DEFAULT.c1,'player ships wear the realm arms');
const foreign=S.arms({allegiance:'foreign',realm:'azure'});
assert.equal(foreign.flag.c1,S.FOREIGN.azure.heraldry.c1,'foreign ships fly their own realm');
assert.equal(foreign.sail,foreign.flag,'and wear it on the sails');
const merchant=S.arms({allegiance:'merchant',realm:'azure'});
assert.equal(merchant.flag.c1,S.FOREIGN.azure.heraldry.c1,'a merchant flies the flag of its realm');
assert.equal(merchant.sail,null,'but its sails stay plain');
for(const [key,m] of Object.entries(M.ships)){
  assert.ok(m.flags.length>=1,key+': has a flag mount');
  assert.ok(m.emblems.length>=1,key+': has a heraldry patch on the sails');
  for(const e of m.emblems)assert.equal(e.v.length,(e.cols+1)*(e.rows+1)*3,key+': patch grid');
  const plain=S.mesh(key,{x:0,y:0},0).col.length;
  const flagTris=m.flags.length*2*10*6,patchTris=m.emblems.reduce((t,e)=>t+e.cols*e.rows*4,0);
  assert.equal(S.mesh(key,{x:0,y:0},0,{...merchant,t:0}).col.length,plain+flagTris,key+': merchant adds flags only');
  const war=S.mesh(key,{x:0,y:0},0,{...foreign,t:0});
  assert.equal(war.col.length,plain+flagTris+patchTris,key+': warship adds flags and sail arms');
  assert.ok(war.col.includes(S.FOREIGN.azure.heraldry.c1),key+': in the realm colours');
}
const len=k=>M.ships[k].L;
assert.ok(Math.min(...S.large.map(len))>1.5*Math.max(...S.small.map(len)),'large ships are clearly longer than small craft');
const w=S.mesh('cocca',{x:10,y:20,heading:Math.PI/2});
assert.equal(w.pos.length,w.col.length*9,'world mesh: one colour per triangle');
const ys=w.pos.filter((_,i)=>i%3===1);
assert.ok(Math.max(...ys)-Math.min(...ys)>=M.ships.cocca.L*.95,'heading turns the ship in the world');
console.log('PASS ships: 3 small + 2 large Blender models, Asset Lab entries, waterline, proportions, world placement');
