'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const M=require('../march/engine.js');
const root=path.resolve(__dirname,'..');
const page=fs.readFileSync(path.join(root,'march/index.html'),'utf8');
const ui=fs.readFileSync(path.join(root,'march/ui.js'),'utf8');
assert.match(page,/engine\.js/);
assert.match(page,/ui\.js/);
assert.match(page,/TEST LOCALE/);
assert.match(ui,/M\.withdraw\(state\)/);
const s=M.initial();
assert.ok(M.valid(s));
assert.equal(s.fiefs.length,4);
assert.equal(M.reportAssaultVictory(s),false,'no unearned siege victory');
const enemy=s.fiefs.find(f=>f.id==='hollowmere');
const original=structuredClone(enemy);
const route=M.pathfind(s.company,{x:enemy.x,y:enemy.y});
assert.ok(route.length>0);
assert.equal(M.march(s,enemy.x,enemy.y),true);
assert.equal(s.company.route.length,route.length);
M.advance(s,route.length);
assert.equal(M.currentTarget(s).id,enemy.id);
assert.equal(s.operation.phase,'approach');
assert.equal(M.conquer(s),false,'cannot annex before a military outcome');
const stolen=M.raid(s);
assert.ok(stolen&&Object.values(stolen).some(n=>n>0),'raid must capture real, finite stock');
assert.ok(enemy.stock.food<original.stock.food||enemy.stock.gold<original.stock.gold);
assert.ok(enemy.damage.civil>original.damage.civil,'partial destruction persisted');
assert.equal(enemy.owner,'enemy','raid is never an automatic conquest');
const raidedDamage=enemy.damage.civil;
const cargo=M.cargoUsed(s);
assert.equal(M.withdraw(s),true,'voluntary withdrawal at any stage');
assert.equal(s.operation,null);
assert.equal(enemy.owner,'enemy');
assert.equal(enemy.damage.civil,raidedDamage,'retreat does not undo the raid');
assert.equal(M.cargoUsed(s),cargo,'retreat does not discard captured stock');
assert.equal(M.march(s,enemy.x,enemy.y),true,'may immediately return or start another operation');
assert.equal(M.besiege(s),true);
assert.equal(M.conquer(s),false,'siege is not conquest');
assert.equal(M.reportAssaultVictory(s),false,'cannot mark immediate breach');
M.advance(s,2);
assert.equal(s.operation.phase,'siege');
assert.equal(enemy.owner,'enemy','elapsed siege days do not auto-annex');
assert.equal(M.reportAssaultVictory(s),true,'only test adapter supplies a resolved victory');
assert.equal(enemy.owner,'enemy','successful assault still requires conquest choice');
assert.equal(M.conquer(s),true);
assert.equal(enemy.owner,'player');
assert.equal(s.operation,null,'campaign continues after conquest');
assert.ok(M.pathfind({x:3,y:3},{x:7,y:3}).some(p=>p.x===4&&p.y===3),
  'crossing the water bottleneck must use the bridge');
assert.equal(M.march(s,4,2),false,'impassable water cannot be a target');
const enemy2=s.fiefs.find(f=>f.id==='thornwatch');
M.march(s,enemy2.x,enemy2.y);
M.advance(s,30);
assert.equal(s.operation?.phase,'approach');
M.besiege(s);
M.advance(s,1);
assert.equal(M.withdraw(s),true,'must be free to abort even an active siege');
assert.equal(enemy2.owner,'enemy');
assert.ok(s.fiefs.every(f=>['food','wood','gold'].every(k=>f.stock[k]>=0)));
const store=new Map();
const storage={getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value)};
assert.equal(M.save(s,storage),true);
const loaded=M.load(storage);
assert.equal(loaded.day,s.day);
assert.equal(loaded.fiefs.find(f=>f.id==='hollowmere').owner,'player');
assert.equal(loaded.fiefs.find(f=>f.id==='hollowmere').damage.civil,raidedDamage);
assert.equal(M.march(loaded,enemy.x,enemy.y),true,'return to a conquered fief to deliver loot');
M.advance(loaded,loaded.company.route.length);
assert.equal(M.unload(loaded)>0,true,'company may deposit raid loot at conquered fief');
assert.equal(M.cargoUsed(loaded),0,'deposited loot clears company load');
store.set(M.KEY,'{"version":7}');
assert.ok(M.valid(M.load(storage)),'unknown schema resets to sandbox fixture');
console.log('MARCH skeleton: routing, partial raiding, withdrawal, optional conquest, persistence PASS');
