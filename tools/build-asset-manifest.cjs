#!/usr/bin/env node
'use strict';
// Generates src/asset-manifest.js: every authored PNG/SVG under src/assets for the Asset Lab.
// Folders named *_rotations hold one frame per heading (name_000.svg, name_015.svg, ...):
// they are listed as rotation sets, not as separate assets.
//   node tools/build-asset-manifest.cjs          write the manifest
//   node tools/build-asset-manifest.cjs --check  fail if the checked-in manifest is stale
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const OUT='src/asset-manifest.js';

function scan(){
  const files=[],rotations={};
  (function walk(dir){
    const entries=fs.readdirSync(path.join(root,dir),{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name));
    for(const entry of entries){
      const rel=path.posix.join(dir,entry.name);
      if(entry.isDirectory()){
        if(entry.name.endsWith('_rotations')){
          const frames=fs.readdirSync(path.join(root,rel)).filter(n=>/_(\d{3})\.(png|svg)$/i.test(n)).sort();
          if(frames.length)rotations[rel]=frames.map(n=>({deg:Number(/_(\d{3})\./.exec(n)[1]),file:path.posix.join(rel,n)}));
          continue;
        }
        walk(rel);
      }else if(/\.(png|svg)$/i.test(entry.name))files.push(rel);
    }
  })('src/assets');
  return{files,rotations};
}
function render({files,rotations}){
  return '// GENERATED by tools/build-asset-manifest.cjs - do not edit by hand.\n'+
    'window.CONQUER_ASSET_FILES='+JSON.stringify(files,null,1)+';\n'+
    'window.CONQUER_ASSET_ROTATIONS='+JSON.stringify(rotations)+';\n';
}
const text=render(scan());
if(process.argv.includes('--check')){
  const current=fs.existsSync(path.join(root,OUT))?fs.readFileSync(path.join(root,OUT),'utf8').replace(/\r\n/g,'\n'):'';
  if(current!==text){console.error(OUT+' is stale: run node tools/build-asset-manifest.cjs');process.exit(1)}
  console.log(OUT+' up to date');
}else{
  fs.writeFileSync(path.join(root,OUT),text);
  console.log('Wrote '+OUT);
}
