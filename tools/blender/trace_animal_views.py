"""Trace the part-ID renders of animal_views.py into the animals' views module (ANIMAL-VIEWS-261127).

  python tools/blender/trace_animal_views.py <output .js> <species>=<render dir> [...]

Same tracing as the mounted figures (trace_mounted_views.py): each image is split by ID colour into
the visible region of each part, traced and written in the animal's art units (relative to the
ground centre, y down, facing right). Fills are coat colour tokens; each group is outlined in the
art's own line colour (legs legLine, head/neck/ears headLine, horns hornLine, body/tail line).
"""
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from trace_mounted_views import ANGLES, regions_of, token_of  # noqa: E402

OUTLINE = (("leg", "coat:legLine"), ("head", "coat:headLine"), ("neck", "coat:headLine"), ("ear", "coat:headLine"),
           ("antler", "coat:headLine"), ("horn", "coat:hornLine"), ("body", "coat:line"), ("tail", "coat:line"))


def outline_of(group, coat):
    for prefix, token in OUTLINE:
        if group.startswith(prefix):
            return token if token[5:] in coat else "coat:line"
    return "coat:line"


def trace_species(src):
    meta = json.load(open(os.path.join(src, "ids.json"), encoding="utf-8"))
    coat, livery = meta["colors"]["coat"], meta["colors"]["livery"]
    ppm = meta["res"] / meta["ortho"]
    keys = list(meta["ids"].keys())
    keys_rgb = np.array([[int(c) for c in k.split(",")] for k in keys])
    meta["_parts"] = [meta["ids"][k] for k in keys]
    parts = [{"k": p["k"], "group": p["group"], "fill": token_of(p["style"], p["group"], coat, livery),
              "outline": outline_of(p["group"], coat)} for p in meta["_parts"]]
    poses = meta["sets"][0]["poses"]
    views = {}
    for view in meta["views"]:
        frames = [regions_of(os.path.join(src, f"{view}_{pose}__base.png"), meta, keys_rgb, ppm, {"base"}) for pose in poses]
        a = math.radians(ANGLES[view])
        views[view] = {"shadow": round(78 * abs(math.cos(a)) + 30 * abs(math.sin(a)), 1), "frames": frames}
    print("traced", meta.get("species"), src)
    return {"parts": parts, "poses": poses, "views": views}


def main():
    out = sys.argv[1]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/blender/trace_animal_views.py (Blender build: tools/blender/animal_views.py,\n")
        f.write("// parts from the approved 2D art: extract_animal_parts.mjs). Do not edit by hand.\n")
        f.write("window.ConquerAnimalViews=window.ConquerAnimalViews||{};\n")
        for arg in sys.argv[2:]:
            species, src = arg.split("=", 1)
            f.write(f"window.ConquerAnimalViews[{json.dumps(species)}]=" + json.dumps(trace_species(src), separators=(",", ":")) + ";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
