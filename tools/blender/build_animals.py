"""CONQUER 3D animals builder (Blender 5.x) — horse first.

Low-poly rigid parts with pivots at the joints (hips, shoulders, neck base,
throat, tail root), so the game drives the same walk / browse / run poses as
the 2D animals by turning parts about their pivots. Colours are coat *roles*
(coat, coatDark, mane, hoof, eye, muzzle) resolved in game against the species'
coat palette, so every coat variant works in 3D.

Run inside Blender (BlenderMCP execute_code):
    CQ_DIR = r"...\\ASSETS\\blender"; ANIMALS_OUT = r"...\\src\\assets\\animal-models.js"
    exec(open(CQ_DIR + r"\\build_animals.py", encoding="utf-8").read())
Axes: +X forward (nose), +Y left, +Z up; origin on the ground under the barrel.
"""
import json, math, os, sys, importlib
from mathutils import Vector
_here = os.path.dirname(os.path.abspath(__file__)) if '__file__' in globals() else CQ_DIR
if _here not in sys.path:
    sys.path.insert(0, _here)
import cq_blender
importlib.reload(cq_blender)
from cq_blender import Part, fresh_collection, export_part, u

# Display palette for Blender only (a bay horse); the game recolours by role.
ROLES = {'coat': '#8a5a35', 'coatDark': '#6d4628', 'mane': '#2a1a10', 'hoof': '#221812',
         'eye': '#120c08', 'muzzle': '#5e3d24'}
KEYS = list(ROLES.keys())
COLL_NAME = 'CONQUER_Animals'


def build_horse(root):
    parts, pivots = {}, {}
    P = lambda name, off=(0, 0, 0): Part(root, name, ROLES, off)

    p = P('body')
    # Barrel along x, oval section (taller than wide), rump left, chest right.
    p.cylinder(.3, 0, 'coat', n=8, axis='x', center=(0, 0, 1.22), squash=1.12,
               radii=[.14, .29, .34, .34, .31, .2], along=[-1.02, -.86, -.4, .3, .72, .9], cap_key='coatDark')
    parts['body'] = p.finish()

    # Legs: hind near/far, fore near/far (+y is the left side). Each leg is one rigid
    # part (thigh/forearm + cannon + hoof) turning about its hip or shoulder.
    legs = [('legHL', -.62, .17, 1.12), ('legHR', -.62, -.17, 1.12), ('legFL', .6, .17, 1.06), ('legFR', .6, -.17, 1.06)]
    for name, x, y, z in legs:
        p = P(name)
        hind = name.startswith('legH')
        knee = (x + (-.06 if hind else .02), y, .6)
        p.taper((x, y, z), knee, .2 if hind else .17, .26 if hind else .2, .11, .11, 'coat')
        p.taper(knee, (x, y, .1), .1, .1, .08, .08, 'coat')
        p.box((x, y, .05), (.13, .11, .1), 'hoof')
        parts[name] = p.finish()
        pivots[name] = u(x, y, z)

    # Neck from the withers to the throat, mane along its crest.
    p = P('neck')
    p.taper((.6, 0, 1.3), (1.25, 0, 2.15), .3, .48, .2, .28, 'coat')
    p.taper((.54, 0, 1.62), (1.2, 0, 2.3), .08, .1, .06, .09, 'mane')
    parts['neck'] = p.finish()
    pivots['neck'] = u(.74, 0, 1.42)

    # Head hangs from the poll, nose down and forward; ears, eyes, darker muzzle.
    p = P('head')
    p.taper((1.21, 0, 2.21), (1.65, 0, 1.75), .24, .32, .17, .2, 'coat', end_key='muzzle')
    for s in (-1, 1):
        p.taper((1.25, s * .06, 2.27), (1.2, s * .08, 2.45), .06, .05, .015, .015, 'coat')
        p.box((1.37, s * .105, 2.12), (.05, .02, .04), 'eye')
    parts['head'] = p.finish()
    pivots['head'] = u(1.27, 0, 2.13)

    p = P('tail')
    p.taper((-.98, 0, 1.38), (-1.12, 0, .62), .1, .12, .14, .05, 'mane')
    parts['tail'] = p.finish()
    pivots['tail'] = u(-.98, 0, 1.38)
    return parts, pivots


def main(out_path):
    root = fresh_collection(COLL_NAME)
    horse, pivots = build_horse(root)
    data = {'roles': KEYS, 'horse': {
        'parts': {name: export_part(part, KEYS) for name, part in horse.items()},
        'pivots': pivots,
        'legs': ['legHL', 'legHR', 'legFL', 'legFR'],
        'height': u(2.45)[0], 'center': u(0, 0, 1.22),
    }}
    js = ("'use strict';\n// Generated by ASSETS/blender/build_animals.py — do not edit by hand.\n"
          "// Animal parts as triangles in model space (U): +x forward, +y left, +z up; colours are coat roles.\n"
          "window.ConquerAnimalModels=" + json.dumps(data, separators=(',', ':')) + ";\n")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    tris = sum(len(p['c']) for p in data['horse']['parts'].values())
    print(f"animal models: horse {tris} triangles, {len(js) // 1024} KB -> {out_path}")
    return tris


if __name__ == '__main__' and '--' in sys.argv:
    args = sys.argv[sys.argv.index('--') + 1:]
    main(args[args.index('--out') + 1])
elif 'ANIMALS_OUT' in globals():
    ANIMALS_RESULT = main(ANIMALS_OUT)
